/**
 * Turning "these dependencies are missing" into something the user can actually
 * finish.
 *
 * The first version of this ran `sudo apt install …` from a child process with
 * piped stdio. `sudo` cannot read a password without a terminal, so it failed
 * with "no tty present and no askpass program specified" — while the wizard
 * promised a password box would appear. Nothing ever could: there was no
 * terminal and no askpass helper. The user saw a red sudo error and no way
 * forward.
 *
 * So the install is now handed to a terminal window the user can type into.
 * These functions build the command and the script that window runs. They are
 * pure so the shapes can be checked without a desktop session.
 */

/**
 * Debian package names apt will accept. The character set is the policy set
 * (`a-z`, digits, `+`, `-`, `.`), so a value that matches cannot break out of
 * a shell word. Callers still pass the names as argv elements.
 */
const DEBIAN_PACKAGE_NAME = /^[a-z0-9][a-z0-9+.-]{0,127}$/

export class InvalidPackageNameError extends Error {
  readonly packageName: string

  constructor(packageName: string) {
    super(`invalid Debian package name: ${JSON.stringify(packageName)}`)
    this.name = 'InvalidPackageNameError'
    this.packageName = packageName
  }
}

export function isDebianPackageName(name: string): boolean {
  return DEBIAN_PACKAGE_NAME.test(name)
}

export function assertDebianPackageName(name: string): string {
  if (!isDebianPackageName(name)) throw new InvalidPackageNameError(name)
  return name
}

export interface DependencyInstallPlan {
  /** Debian package names, deduplicated and sorted, passed to apt in one go. */
  packages: string[]
  /**
   * The command a person can read and re-run. Built only from validated
   * package names. The terminal script does not eval this string.
   */
  command: string | null
  /** `sudo apt-get update`, or `null` when nothing is missing. */
  updateArgv: string[] | null
  /** `sudo apt-get install -y -- <packages>`, or `null` when nothing is missing. */
  installArgv: string[] | null
}

/**
 * The names `checkDependencies` reports are already apt package names, so no
 * mapping table is needed. Notably npm is installed from the distribution
 * rather than the NodeSource repository the earlier version reached for:
 * NodeSource adds a third-party apt source to the user's machine, its setup
 * script needs a terminal of its own, and Kali's own npm is current (npm 11 on
 * node 24, checked on Kali 2026.1). A user who wants NodeSource can still run
 * it themselves — the plan is shown in full either way.
 */
export function buildDependencyInstallPlan(
  missing: readonly string[],
): DependencyInstallPlan {
  const packages = [
    ...new Set(
      missing
        .map((name) => name.trim())
        .filter((name) => name.length > 0)
        .map((name) => assertDebianPackageName(name)),
    ),
  ].sort()

  if (packages.length === 0) {
    return { packages: [], command: null, updateArgv: null, installArgv: null }
  }

  const updateArgv = ['sudo', 'apt-get', 'update']
  const installArgv = ['sudo', 'apt-get', 'install', '-y', '--', ...packages]

  return {
    packages,
    updateArgv,
    installArgv,
    command: `sudo apt-get update && sudo apt-get install -y -- ${packages.join(' ')}`,
  }
}

/**
 * The script the terminal runs.
 *
 * It is written to a file rather than passed as `bash -lc "…"` because terminal
 * emulators disagree about how that string is split: some shell-parse `-e`, some
 * exec it directly. A file sidesteps the quoting entirely, and it keeps the
 * window open at the end so the apt output is still readable afterwards — the
 * emulators have no common "hold" flag.
 *
 * Everything the user needs to know is printed here rather than only in the app,
 * because the app cannot tell when the install finishes: it handed the work to
 * another window.
 */
export function renderInstallScript(plan: DependencyInstallPlan): string {
  if (!plan.command) {
    return [
      '#!/bin/bash',
      '# Generated by Claude Code Manager. Safe to delete.',
      'echo "没有缺失的系统依赖。"',
      '',
    ].join('\n')
  }

  // Names are validated before they reach this string. They are still
  // passed to apt as `"${packages[@]}"`, not by eval'ing `plan.command`.
  const quoted = plan.packages.map((name) => `'${name.replaceAll("'", "'\\''")}'`).join('\n  ')

  return `#!/bin/bash
# Generated by Claude Code Manager — installs the system packages it needs.
# Safe to delete; nothing else reads it.

set -u

packages=(
  ${quoted}
)

echo "Claude Code Manager 需要安装这些系统软件包："
echo "  ${plan.packages.join(' ')}"
echo
echo "接下来 sudo 会让你输入系统密码（输入时屏幕上不会显示）。"
echo

if sudo apt-get update && sudo apt-get install -y -- "\${packages[@]}"; then
  echo
  echo "安装完成。请回到 Claude Code Manager 窗口，点「重新检测」。"
else
  status=$?
  echo
  echo "安装失败（退出码 $status）。常见原因：密码输入错误、没有网络、或 apt 正被其他程序占用。"
  echo "也可以自己复制这行命令手动执行："
  echo
  echo "  ${plan.command}"
fi

echo
read -n 1 -s -r -p "按任意键关闭此窗口..."
echo
`
}
