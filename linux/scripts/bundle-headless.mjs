/**
 * Bundle the headless installer driver into a single self-contained file.
 *
 * The engine imports nothing but Node builtins, which is what makes this
 * possible: the output needs no `node_modules`, no `npm install`, and no
 * Electron on the target machine. That matters because the GUI cannot start on a
 * headless VM, so a terminal driver is the only way to exercise the real
 * pipeline there.
 *
 * Usage: node scripts/bundle-headless.mjs [outfile]
 */

import { build } from 'esbuild'
import { mkdirSync, statSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join, resolve } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..')
const outfile = resolve(root, process.argv[2] ?? join('dist-installer', 'ccm-installer.cjs'))

mkdirSync(dirname(outfile), { recursive: true })

const result = await build({
  entryPoints: [join(root, 'src', 'main', 'installer', 'cli-headless.ts')],
  outfile,
  bundle: true,
  platform: 'node',
  // CommonJS so the output runs on any Node 18+ without a package.json nearby
  // declaring `"type": "module"`.
  format: 'cjs',
  target: 'node20',
  // Node builtins stay external; there is no third-party dependency to bundle.
  packages: 'external',
  minify: false,
  sourcemap: false,
  banner: {
    js: [
      '#!/usr/bin/env node',
      '/*',
      ' * Claude Code Manager — headless installer pipeline driver.',
      ' *',
      ' * Generated by scripts/bundle-headless.mjs. Do not edit; edit',
      ' * src/main/installer/cli-headless.ts instead.',
      ' *',
      ' * Requires: Node.js 20+, tar with xz support, and a writable ~/.',
      ' * Commands are read-only except `install`.',
      ' */',
    ].join('\n'),
  },
  metafile: true,
  logLevel: 'warning',
})

const { size } = statSync(outfile)
const inputs = Object.keys(result.metafile.inputs).length

console.log(`bundled  ${outfile}`)
console.log(`size     ${(size / 1024).toFixed(1)} KB`)
console.log(`modules  ${inputs}`)
console.log(`deps     none (Node builtins only)`)
